export function getCaseCardCopy(caseStudy: CaseStudy, locale: CaseLocale) {
  const localized = caseStudy.localized?.[locale];

  return {
    title: localized?.cardTitle ?? caseStudy.title,
    category: localized?.category ?? caseStudy.category,
    label: localized?.label ?? caseStudy.label,
    short: localized?.short ?? caseStudy.short,
  };
}

export function getCasePageContent(caseStudy: CaseStudy, locale: CaseLocale) {
  return caseStudy.localized?.[locale] ?? null;
}

